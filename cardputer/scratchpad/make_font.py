ZERO = [0x00]*8
glyphs = {c: ZERO for c in range(FIRST, LAST + 1)}

for ch, rows in UP.items():
    glyphs[ord(ch)] = rows            # uppercase
    glyphs[ord(ch.lower())] = rows    # lowercase mirrors uppercase (UI is all-caps)
for ch, rows in DIGIT.items():
    glyphs[ord(ch)] = rows
for ch, rows in PUNCT.items():
    glyphs[ord(ch)] = rows

def line(code):
    rows = glyphs[code]
    body = ", ".join(f"0x{b:02x}" for b in rows)
    label = '' if code in (0x20, 0x5c) else chr(code)   # 0x5c would make the // comment a line-continuation
    return f"    [0x{code:02x} - FONT_FIRST] = {{ {body} }},   // 0x{code:02x} {label}"

out = []
out.append("// font8x8.h - a compact 6x7 bitmap font in an 8x8 cell (byte = one row,")
out.append("// bit0 = left column). Covers A-Z, a-z, 0-9 and common punctuation so any")
out.append("// menu label renders in full. Regenerate with scratchpad/make_font.py.")
out.append("#pragma once")
out.append("#include <stdint.h>")
out.append("")
out.append(f"#define FONT_FIRST 0x{FIRST:02x}")
out.append(f"#define FONT_LAST  0x{LAST:02x}")
out.append("")
out.append("static const uint8_t FONT8X8[FONT_LAST - FONT_FIRST + 1][8] = {")
for code in range(FIRST, LAST + 1):
    out.append(line(code))
out.append("};")
out.append("")

text = "\n".join(out)
import sys
dest = sys.argv[1] if len(sys.argv) > 1 else "/dev/stdout"
with open(dest, "w") as f:
    f.write(text)
print(f"wrote {dest}: {len(text)} bytes, {LAST-FIRST+1} glyphs")
